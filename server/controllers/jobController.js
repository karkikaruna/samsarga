export const updateJob = catchAsyncErrors(async (req, res, next) => {
  const { role } = req.user;
  if (role === "Job Seeker") {
    return next(
      new ErrorHandler("Job Seeker are not allowed to access this resource.", 400)
    );
  }
  const { id } = req.params;//it specify which job should be updateds
  let job = await Job.findById(id);
  if (!job) {
    return next(new ErrorHandler("Job not found!", 404));
  }
  job = await Job.findByIdAndUpdate(id, req.body, {
    new: true,
    runValidators: true,
    useFindAndModify: false,
  });
  res.status(200).json({
    success: true,
    message: "Job Updated!",
  });
});

